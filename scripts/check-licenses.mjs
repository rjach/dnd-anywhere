// Lists licenses of runtime dependencies shipped in the extension, writes
// THIRD_PARTY_NOTICES.md, and fails on copyleft licenses we can't ship under MIT.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const FORBIDDEN = /\b(A?GPL|LGPL|SSPL|EUPL|CC-BY-SA)\b/i;

const output = execFileSync(
  "pnpm",
  ["licenses", "list", "--prod", "--json", "--filter", "extension"],
  {
    cwd: ROOT,
    encoding: "utf8",
  },
);
const byLicense = JSON.parse(output || "{}");
const packages = [];
for (const [license, entries] of Object.entries(byLicense)) {
  for (const entry of entries) {
    packages.push({
      name: entry.name,
      versions: entry.versions ?? [entry.version],
      license,
      paths: entry.paths ?? [],
    });
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name));

const blocked = packages.filter((pkg) => FORBIDDEN.test(pkg.license));
if (blocked.length > 0) {
  console.error("Copyleft licenses in shipped dependencies:");
  for (const pkg of blocked) console.error(`  ${pkg.name}: ${pkg.license}`);
  process.exit(1);
}

const sections = [];
for (const pkg of packages) {
  let text = "";
  for (const path of pkg.paths) {
    for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license"]) {
      try {
        text = await readFile(join(path, name), "utf8");
        break;
      } catch {
        // try the next file name
      }
    }
    if (text) break;
  }
  sections.push(
    `## ${pkg.name} ${pkg.versions.join(", ")} (${pkg.license})\n\n${text ? "```\n" + text.trim() + "\n```" : "License text not bundled with the package."}`,
  );
}

const notices = `# Third-party notices\n\nDnD Anywhere ships the following open-source packages. This file is generated by \`pnpm check:licenses\`.\n\n${sections.join("\n\n")}\n`;
await writeFile(join(ROOT, "THIRD_PARTY_NOTICES.md"), notices);
console.log(
  `Licenses ok for ${packages.length} shipped package(s): ${packages.map((p) => `${p.name} (${p.license})`).join(", ")}`,
);
